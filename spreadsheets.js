const rankList=document.getElementById('sheet-ranks');
const lessonPanel=document.getElementById('sheet-lesson');
function videoId(url){try{const u=new URL(url);if(u.hostname==='youtu.be')return u.pathname.slice(1);if(u.hostname.endsWith('youtube.com'))return u.searchParams.get('v')||u.pathname.split('/embed/')[1];}catch(e){}return null;}
function selectSpreadsheetLesson(index){
 const lesson=spreadsheetLessons[index];
 document.querySelectorAll('.sheet-rank').forEach((button,i)=>{button.classList.toggle('active',i===index);button.setAttribute('aria-current',i===index?'true':'false');});
 lessonPanel.replaceChildren();
 const heading=document.createElement('h3');heading.textContent=lesson.Level;lessonPanel.append(heading);
 const grid=document.createElement('div');grid.className='sheet-grid';
 const id=videoId(lesson.VideoURL);
 if(id&&/^[a-zA-Z0-9_-]{11}$/.test(id)){
  const video=document.createElement('div');video.className='sheet-video';
  const iframe=document.createElement('iframe');iframe.src='https://www.youtube-nocookie.com/embed/'+id;iframe.title=lesson.Level+' tutorial';iframe.allow='accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share';iframe.allowFullscreen=true;iframe.referrerPolicy='strict-origin-when-cross-origin';video.append(iframe);grid.append(video);
 }
 const action=document.createElement('div');action.className='sheet-action';
 const sub=document.createElement('h4');sub.textContent=index===0?'Welcome!':'Practice Material';action.append(sub);
 const para=document.createElement('p');para.textContent=index===0?'Choose a rank to begin your spreadsheet lessons.':'Open the spreadsheet to complete the '+lesson.Level+' tasks.';action.append(para);
 if(lesson.PracticeLink&&lesson.PracticeLink!=='#'){
  const link=document.createElement('a');link.href=lesson.PracticeLink;link.target='_blank';link.rel='noopener noreferrer';link.textContent='📊 Open Spreadsheet';action.append(link);
 }
 grid.append(action);lessonPanel.append(grid);
}
spreadsheetLessons.forEach((lesson,index)=>{
 const button=document.createElement('button');button.type='button';button.className='sheet-rank';
 const shield=document.createElement('span');shield.className='sheet-shield';shield.style.backgroundColor=spreadsheetRankColors[lesson.Level]||'#38bdf8';
 button.append(shield,document.createTextNode(lesson.Level==='New'?'Introduction':lesson.Level));button.addEventListener('click',()=>selectSpreadsheetLesson(index));rankList.append(button);
});
